from abc import ABC,abstractmethod
from .models import TableDefinition,ColumnDefinition,Capabilities
class RelationalDataStore(ABC):
    @property
    @abstractmethod
    def engine_name(self)->str: ...
    @property
    @abstractmethod
    def capabilities(self)->Capabilities: ...
    @abstractmethod
    def list_tables(self,database): ...
    @abstractmethod
    def describe_table(self,database,table): ...
    @abstractmethod
    def read_rows(self,database,table,page,page_size): ...
    @abstractmethod
    def insert_row(self,database,table,values): ...
    @abstractmethod
    def update_row(self,database,table,key,values): ...
    @abstractmethod
    def delete_row(self,database,table,key): ...
    @abstractmethod
    def create_table(self,database,definition:TableDefinition): ...
    @abstractmethod
    def add_column(self,database,table,column:ColumnDefinition): ...
    @abstractmethod
    def alter_column(self,database,table,current_name,replacement:ColumnDefinition): ...
